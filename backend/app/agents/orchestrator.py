# 8. Build LangGraph


builder = StateGraph(AgentState)


# Add Nodes


builder.add_node("supervisor", supervisor_node)

builder.add_node(
    "coding_agent",
    coding_agent,
)

builder.add_node(
    "research_agent",
    research_agent,
)

builder.add_node(
    "rag_agent",
    rag_agent,
)

builder.add_node(
    "reviewer_agent",
    reviewer_agent,
)


# 9. Define Graph Edges


# START → Supervisor

builder.add_edge(
    START,
    "supervisor",
)

# Supervisor → Selected Agent


builder.add_conditional_edges(
    "supervisor",
    lambda state: state["next_agent"],
    {
        "coding_agent": "coding_agent",
        "research_agent": "research_agent",
        "rag_agent": "rag_agent",
        "reviewer_agent": "reviewer_agent",
    },
)



builder.add_edge(
    "coding_agent",
    "reviewer_agent",
)

builder.add_edge(
    "research_agent",
    "reviewer_agent",
)

builder.add_edge(
    "rag_agent",
    "reviewer_agent",
)



builder.add_edge(
    "reviewer_agent",
    END,
)



graph = builder.compile()


